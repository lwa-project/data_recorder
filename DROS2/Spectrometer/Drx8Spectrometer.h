#define DRX8_SPECTROMETER_REPORT_INTERVAL 30000
#define DRX8_SPECTRA_MAGIC1 0xC0DEC0DE
#define DRX8_SPECTRA_MAGIC2 0xED0CED0C

typedef struct __Drx8SpectraHeader{
	uint32_t			MAGIC1;     // must always equal 0xC0DEC0DE
	uint64_t 			timeTag0;
	uint16_t 			timeOffset;
	uint16_t 			decFactor;
	uint32_t 			freqCode[2];
	uint32_t			fills[4];
	uint8_t				errors[4];
	uint8_t 			beam;
	uint8_t				stokes_format;
	uint8_t				spec_version;
	union{
		struct {
			uint8_t		flag_xcp:1;
			uint8_t		flag_reserved:5;
			uint8_t		flag_k:2; // kurtosis
		};
		uint8_t			reserved;
	};
	union{
		uint32_t 		nFreqs;
		uint32_t 		nPerFrame;
	};
	uint32_t 			nInts;
	uint32_t 			satCount[4];
	uint32_t			MAGIC2;     // must always equal 0xED0CED0C
} __attribute__((packed)) Drx8SpectraHeader;

enum Drx8Comp{ BEFORE8, COMPAT8_BEFORE, COMPAT8_IN, COMPAT8_AFTER, INCOMPAT8 };
enum Drx8BlockState{ BS8_UNUSED=0, BS8_FILLING, BS8_STARTABLE, BS8_PROCESSING, BS8_DONE, BS8_DROPPED};
#define FREQ8_CODE_UNINITIALIZED (uint32_t)0xFEEDBEEF
#define DRX8_TUN_0 1
#define MAX8_SIMULTANEOUS_BLOCKS_PROCESSING 1

enum BlockStages {FILLING8, PROCESSING8, DONE8}; // implicit invalid stage

typedef struct __Drx8BlockSetup{
	__Drx8BlockSetup():
		//state(BS8_EMPTY),
		//spc_block_index(0),
		//ticketFrameIndex(0),
		bIdx((size_t)(-1ll)),
		timeTag0(0),
		timeTagN(0),
		stepPhase(0),
		timeTagStep(0),
		decFactor(0),
		timeOffset(0),
		beam(0),
		freqCode()
		{
		freqCode[0]=FREQ8_CODE_UNINITIALIZED;
		freqCode[1]=FREQ8_CODE_UNINITIALIZED;
	}
	Drx8BlockState       state;
	size_t              bIdx; // block index into the spectrometer buffer
	uint64_t 			timeTag0;
	uint64_t 			timeTagN;
	uint64_t 			stepPhase;
	uint64_t 			timeTagStep;
	uint16_t 			decFactor;
	uint16_t 			timeOffset;
	uint8_t 			beam;
	uint32_t 			freqCode[2];
//	bool                ownsTicketFrame;
	uint64_t 			insertionCount;
	Drx8SpectraHeader*   header;
	float*              data;
	bool                error;
}__attribute__((packed))  Drx8BlockSetup;

typedef struct __Spectrometer8Counters{
	uint32_t				framesReceived;
	uint32_t				framesInserted;
	uint32_t				framesInsertedExisting;
	uint32_t				framesInsertedNew;
	uint32_t				framesInsertedFresh;
	uint32_t				framesInsertedStale;
	uint32_t				framesDroppedArrivedLate;
	uint32_t				framesDroppedArrivedLate_alt;
	uint32_t				framesDroppedIncompatible;
	uint32_t				framesStalledWaitingBlock;
	uint32_t				framesStalledBlockUnstartable;

	uint32_t				blocksStarted;
	uint32_t				blocksStartedFull;
	uint32_t				blocksStartedHighWater;
	uint32_t				blocksDropped;
	uint32_t				blocksDroppedUnderfull;
	uint32_t				blocksCompleted;

	uint32_t				checkBlockDone_Done;
	uint32_t				checkBlockDone_NotDone;
	uint32_t				checkBlockDone_NotComputing;
	uint32_t				checkBlockDone_WaitFree;
	uint32_t				checkBlockDone_Error;
	uint32_t				checkBlockStart_WaitOutbuf;

	uint32_t				illegalFrames;
	uint32_t				incompatibleFrames;

} __attribute__((packed)) Spectrometer8Counters;

class Drx8Spectrometer: public Plugin {
public:

	Drx8Spectrometer(unsigned K, unsigned L, unsigned Nb, ProductType _OutT, TicketBuffer*& _source );
	virtual ~Drx8Spectrometer();

	// external interface
	bool         isShutDown();
	bool         isValid();
	virtual void stopProducing();
	virtual void stopReceiving();

	// the input/output threads
	virtual void run_master();
	virtual void run_slave();

	// input-thread methods
	bool     insert(Drx8Frame* f);
	uint64_t nextTimeTagAfterBlock(Drx8BlockSetup* bs);
	void     initBlockSetup(Drx8BlockSetup* toPrepare, Drx8Frame* f, Drx8BlockSetup* predecessor = NULL);
	bool     blockMatch(Drx8Frame* f, Drx8BlockSetup* bs);
	int      compare(Drx8Frame* f, Drx8BlockSetup* bs);
	bool     unpack(Drx8Frame* f, Drx8BlockSetup* bs);
	bool     frameIsLegal(Drx8Frame* f);

	// output-thread methods
	void startBlock(Drx8BlockSetup* bs, Drx8SpectraHeader* dsh, float* aData);
	bool isDoneOrError(Drx8BlockSetup* bs);
	bool isError(Drx8BlockSetup* bs);
	void initSpectraHeader(Drx8BlockSetup* bs, Drx8SpectraHeader* dsh);
	void resetBlockSetup(Drx8BlockSetup* bs);

	// miscellaneous; help with object buffer manipulation, since we effectively want moves to be atomic (though they aren't, really, but are safe for single producer, single consumer)
	bool canMove(ObjectBuffer<Drx8BlockSetup*>* from, ObjectBuffer<Drx8BlockSetup*>* to); // checks if the head of from is movable to the tail of to
	void doMove(ObjectBuffer<Drx8BlockSetup*>* from,  ObjectBuffer<Drx8BlockSetup*>* to); // moves the head of from to the tail of to
	bool canRemove(ObjectBuffer<Drx8BlockSetup*>* from);
	bool canInsert(ObjectBuffer<Drx8BlockSetup*>* to);

	string getObjName();

	// reporting, runtime, stats, and debugging
	Spectrometer8Counters* getCounters();
	void   printSpecSetup();
	void   printBlockSetup(Drx8BlockSetup* bs);
	void   printFrameSetup(Drx8Frame* f, Drx8BlockSetup* bs=NULL);
	string specReport();
	//void   generateTestPattern(float* specdata);
	void   doPeriodicReport();

private:
	bool 						 valid;                         // flag indicating all data structures are initialized properly
	volatile bool                doneReceiving;                 // flag indicating we are to stop receiving data
	volatile bool                doneProducing;                 // flag indicating we are to stop producing data
	volatile bool                master_stopped;                // flag indicating receiver thread is terminated
	volatile bool                slave_stopped;                 // flag indicating computer thread is terminated

	Drx8BlockSetup*               blocks;                        // buffer to hold all the blocks
	ObjectBuffer<Drx8BlockSetup*> blocks_free;					// all start here
	ObjectBuffer<Drx8BlockSetup*> blocks_startable;				// blocks that have finished filling
	ObjectBuffer<Drx8BlockSetup*> blocks_dropped;                // blocks dropped
	ObjectBuffer<Drx8BlockSetup*> blocks_computing;              // blocks in progcess of computing
	list<Drx8BlockSetup*>         blocks_filling;				// blocks that have started filling
	Drx8BlockSetup                lastFilledBlockSetup;          // cached copy of most-recently-filled block setup
	bool						 lastFilledBlockSetupGood;      // flag indicating cached copy is good (initialized)

	Spectrometer*                spc;                           // our spectrometer buffer/obj
	TicketBuffer*                source;                        // out input buffer (mainly used through plugin interface)
	unsigned                     freqCount_or_samp_per_frame;   // number of frequency channels
	unsigned                     intCount;                      // number of integrations
	unsigned                     blockCount;                    // number of blocks (both block info and spectrometer obj (linked))
	ProductType                  OutT;                          // output format
	volatile bool                _is_shutdown;                  // flag indicating we're shutdown (so don't free any more resources)
	Spectrometer8Counters         counters;                      // statictics

	size_t                       minTimeTag;                    // earliest legal time tag an input frame can have
	PeriodicReportTimer          rptTimer;

	size_t					     outputHeaderSize;              // size of header
	size_t					     outputDataSize;                // size of spectra
	size_t					     outputBlockSize;               // size of spectra+header
	size_t					     inputFramesPerCell;
	size_t					     inputFramesPerBlock;

/////////////////////////////////////////////////////////////////////
// Static interface                                                //
/////////////////////////////////////////////////////////////////////
public:
	static TB_Geometry getDrx8BufferSize(unsigned K, ProductType OutT);
};
#endif /* DRX8SPECTROMETER_H_ */
